<?php

namespace X3Group\Bitrix24\Console\Commands;

/**
 * Чем кончилась попытка перепривязки одного портала.
 *
 * Заведено вместо разбора текста результата (str_starts_with($result, 'откат')):
 * счётчики прогона — то, по чему оператор судит, стало ли лучше, и держаться они
 * должны на типе, а не на формулировке, которую однажды перепишут.
 */
enum ReanchorOutcome
{
    /** Токен админа записан и подтверждён (или проверка пропущена осознанно). */
    case Repaired;

    /** Проверка не подтвердила права — строка возвращена в прежний вид. */
    case RolledBack;

    /**
     * Проверка не подтвердила права, но строку успел переписать кто-то ещё, и откат
     * отменён. Так и задумано: между записью и проверкой в b24_apps мог приехать
     * настоящий обновлённый токен (живой вызов идёт по шине appEvents, слушатель
     * которой сохраняет рефреш), а откат затёр бы его значением, которое Битрикс
     * уже отозвал.
     */
    case RollbackSkipped;
}
